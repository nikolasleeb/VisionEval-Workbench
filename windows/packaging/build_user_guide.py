#!/usr/bin/env python3
"""Generate the repository-level UserGuide.md from canonical bundled pages."""

from __future__ import annotations

import argparse
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
GUIDE = ROOT / "docs" / "user"
OUTPUT = ROOT / "UserGuide.md"
PAGES = [
    "README.md",
    "setup.md",
    "getting-started.md",
    "core-concepts.md",
    "explore.md",
    "create-and-review.md",
    "run.md",
    "compare.md",
    "settings-workspaces-storage.md",
    "data-units-provenance.md",
    "troubleshooting.md",
    "keyboard-shortcuts.md",
    "future-improvements.md",
]


def repository_links(text: str) -> str:
    text = re.sub(r"\]\((images/[^)]+)\)", r"](docs/user/\1)", text)
    text = re.sub(r"\]\((?!https?://|#|/)([a-z0-9-]+\.md(?:#[^)]+)?)\)", r"](docs/user/\1)", text, flags=re.I)
    text = text.replace("](../developer/", "](docs/developer/")
    return text


def render() -> str:
    sections = [
        "<!-- Generated by packaging/build_user_guide.py from docs/user. Do not edit this file directly. -->",
        "# VisionEval Workbench User Guide",
        "",
        "This repository copy is generated from the same Windows guide bundled with VisionEval Workbench 1.0.1.",
    ]
    for index, name in enumerate(PAGES):
        text = repository_links((GUIDE / name).read_text(encoding="utf-8")).strip()
        if index == 0:
            text = re.sub(r"^# VisionEval Workbench User Guide(?: for Windows)?\s*", "", text).strip()
            heading = "## Overview"
        else:
            text = re.sub(r"^# ", "## ", text, count=1)
            heading = ""
        sections.extend(["", "---", ""])
        if heading:
            sections.extend([heading, ""])
        sections.append(text)
    return "\n".join(sections).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("UserGuide.md is stale; run packaging/build_user_guide.py")
        print("UserGuide.md matches the bundled user documentation")
        return
    OUTPUT.write_text(content, encoding="utf-8")
    print("Wrote UserGuide.md")


if __name__ == "__main__":
    main()
